//=============================================================================
// sobel_edge.v  --  Sobel 边缘检测（对应赛题的"目标识别"部分）
//=============================================================================
// 版本: v1.0
//
// 【它解决什么问题】
//   去雾之后画面清晰了，但"目标在哪里"还需要边缘检测。
//   Sobel 算子能找出图像中亮度剧烈变化的区域 —— 也就是物体的轮廓。
//   这是"目标识别"最轻量、最容易在 FPGA 上实现的方案。
//
// 【Sobel 在算什么】
//   对每个像素取 3x3 邻域，算两个方向的"变化率":
//
//     水平方向 Gx = 右边减左边，中间那行权重加倍
//         -1  0  +1
//         -2  0  +2
//         -1  0  +1
//
//     垂直方向 Gy = 下面减上面
//         -1 -2 -1
//          0  0  0
//         +1 +2 +1
//
//   然后取绝对值相加得到边缘强度:  mag = |Gx| + |Gy|
//
//   （标准 Sobel 用开方 sqrt(Gx²+Gy²)，但硬件里开方很贵；
//     |Gx|+|Gy| 是业界常用的近似，效果几乎一样）
//
// 【处理对象】
//   用亮度 y = (R + 2G + B) >> 2 做检测，输出灰度边缘图（R=G=B=mag）。
//   这样只需要一套行缓存，资源省 2/3。
//
// 【流水线】共 8 级（与接口合同一致）
//   行缓存本身贡献 2 级，Sobel 计算 3 级，再补 3 级延迟。
//
// 【边界】
//   前 2 行 / 前 2 列的窗口不完整（行缓存初始化为 0），
//   输出在这些位置没有意义，但不会崩溃。验证时只比对内部区域。
//=============================================================================

`default_nettype none

module sobel_edge #(
    parameter integer LATENCY = 8,
    parameter WIDTH   = 640,
    parameter ADDR_W  = 11
)(
    input  wire        clk,
    input  wire        rst_n,

    input  wire        de_in,
    input  wire        hs_in,
    input  wire        vs_in,
    input  wire [7:0]  r_in,
    input  wire [7:0]  g_in,
    input  wire [7:0]  b_in,

    output wire        de_out,
    output wire        hs_out,
    output wire        vs_out,
    output wire [7:0]  r_out,
    output wire [7:0]  g_out,
    output wire [7:0]  b_out,
    output wire        frame_end
);

    //=========================================================================
    // 0. 亮度
    //=========================================================================
    wire [9:0] y_sum = {2'b00, r_in} + {1'b0, g_in, 1'b0} + {2'b00, b_in};
    wire [7:0] y_pix = y_sum[9:2];

    //=========================================================================
    // 1. 行缓存：拿到 3x3 窗口
    //=========================================================================
    wire [71:0] win;
    wire        win_valid;
    wire        de_lb, hs_lb, vs_lb;

    line_buffer_3x3 #(
        .WIDTH  (WIDTH),
        .PIX_W  (8),
        .ADDR_W (ADDR_W)
    ) u_lb (
        .clk       (clk),
        .rst_n     (rst_n),
        .de_in     (de_in),
        .hs_in     (hs_in),
        .vs_in     (vs_in),
        .pix_in    (y_pix),
        .win_out   (win),
        .win_valid (win_valid),
        .de_out    (de_lb),
        .hs_out    (hs_lb),
        .vs_out    (vs_lb)
    );

    // line_buffer 的输出约定：win[0] 是最左上角，win[8] 是最右下角。
    //
    //   win[0] win[1] win[2]      <- 上上行 (Y-2)
    //   win[3] win[4] win[5]      <- 上一行 (Y-1)，win[4] 是窗口中心
    //   win[6] win[7] win[8]      <- 当前行 (Y)
    //
    wire [7:0] w0 = win[7:0];      // (Y-2, X-2) 左上
    wire [7:0] w1 = win[15:8];     // (Y-2, X-1)
    wire [7:0] w2 = win[23:16];    // (Y-2, X  )
    wire [7:0] w3 = win[31:24];    // (Y-1, X-2)
    wire [7:0] w4 = win[39:32];    // (Y-1, X-1)  窗口中心
    wire [7:0] w5 = win[47:40];    // (Y-1, X  )
    wire [7:0] w6 = win[55:48];    // (Y  , X-2)
    wire [7:0] w7 = win[63:56];    // (Y  , X-1)
    wire [7:0] w8 = win[71:64];    // (Y  , X  ) 右下

    //=========================================================================
    // 2. Sobel 第一级：正权重之和 与 负权重之和
    //=========================================================================
    // 为什么拆成"正和"和"负和"再相减？
    //   直接用有符号数在 Verilog 里容易出错（位宽、符号扩展）。
    //   拆开以后全是无符号加法，最后再比较大小决定符号，安全得多。
    //
    // 窗口排布:
    //   p00 p01 p02
    //   p10 p11 p12
    //   p20 p21 p22
    //=========================================================================
    wire [7:0] p00 = w0, p01 = w1, p02 = w2;
    wire [7:0] p10 = w3, p11 = w4, p12 = w5;
    wire [7:0] p20 = w6, p21 = w7, p22 = w8;

    // Gx 的负权重部分: -p00 - 2*p10 - p20
    // Gx 的正权重部分: +p02 + 2*p12 + p22
    wire [9:0] gx_pos = {2'b00, p02} + {1'b0, p12, 1'b0} + {2'b00, p22};
    wire [9:0] gx_neg = {2'b00, p00} + {1'b0, p10, 1'b0} + {2'b00, p20};

    // Gy 的正权重部分: +p20 + 2*p21 + p22
    // Gy 的负权重部分: -p00 - 2*p01 - p02
    wire [9:0] gy_pos = {2'b00, p20} + {1'b0, p21, 1'b0} + {2'b00, p22};
    wire [9:0] gy_neg = {2'b00, p00} + {1'b0, p01, 1'b0} + {2'b00, p02};

    //=========================================================================
    // 第 3 级：求绝对值（正和减负和，取大的减小的）
    //=========================================================================
    wire [9:0] gx_abs = (gx_pos >= gx_neg) ? (gx_pos - gx_neg) : (gx_neg - gx_pos);
    wire [9:0] gy_abs = (gy_pos >= gy_neg) ? (gy_pos - gy_neg) : (gy_neg - gy_pos);

    reg [10:0] mag_r;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            mag_r <= 11'd0;
        else
            mag_r <= {1'b0, gx_abs} + {1'b0, gy_abs};
    end

    //=========================================================================
    // 第 4 级：饱和到 255
    //=========================================================================
    // |Gx| + |Gy| 最大 1020 + 1020 = 2040，远超 8 位范围，必须饱和。
    // 不饱和的话超过 255 会回绕成小数值，边缘会变成一团糊。
    //=========================================================================
    reg [7:0] mag_out;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            mag_out <= 8'd0;
        else if (mag_r > 11'd255)
            mag_out <= 8'd255;
        else
            mag_out <= mag_r[7:0];
    end

    //=========================================================================
    // 第 5~8 级：延迟补偿
    //=========================================================================
    // 目前总延迟: 行缓存 2 拍 + 三级计算 2 拍 = 4 拍，再补 4 拍到 8。
    //=========================================================================
    reg [7:0] m1, m2, m3, m4;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            m1 <= 8'd0; m2 <= 8'd0; m3 <= 8'd0; m4 <= 8'd0;
        end else begin
            m1 <= mag_out;
            m2 <= m1;
            m3 <= m2;
            m4 <= m3;
        end
    end

    assign r_out = m4;
    assign g_out = m4;
    assign b_out = m4;

    //=========================================================================
    // 同步信号：总延迟必须等于数据通路的 8 拍
    //=========================================================================
    // 数据通路拆解（相对 pix_in 进入的那一拍 t）:
    //   t+1 : 进入 cC0（窗口链）
    //   t+2 : 出现在 win 里
    //   t+3 : mag_r 锁存
    //   t+4 : mag_out 锁存
    //   t+5..t+8 : m1..m4
    //   合计 8 拍 ✓
    //
    // de_lb 已经是 de_in 延迟 2 拍（行缓存内部的链），所以这里再补 6 拍。
    // 【坑】如果这里写成 8 拍，总延迟会变成 10，画面整体偏移 2 个像素。
    //=========================================================================
    reg [5:0] de_sr, hs_sr, vs_sr;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            de_sr <= 6'd0;
            hs_sr <= 6'd0;
            vs_sr <= 6'd0;
        end else begin
            de_sr <= {de_sr[4:0], de_lb};
            hs_sr <= {hs_sr[4:0], hs_lb};
            vs_sr <= {vs_sr[4:0], vs_lb};
        end
    end

    assign de_out = de_sr[5];
    assign hs_out = hs_sr[5];
    assign vs_out = vs_sr[5];

    assign frame_end = 1'b0;

endmodule

`default_nettype wire
